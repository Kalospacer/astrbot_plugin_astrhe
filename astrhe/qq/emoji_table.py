def resolve_emoji(value: str) -> int | None:
    """把含义或编号转成表情 id；不认识返回 None。"""
    text = (value or "").strip()
    if not text:
        return None
    if text.isdigit():
        return int(text)
    meaning = EMOJI_ALIAS.get(text, text)
    return EMOJI_TABLE.get(meaning)


def supported_meanings() -> str:
    """给模型看的含义列表。"""
    return "、".join(EMOJI_TABLE.keys())
